/**
 * Generates prisma/postgres/schema.prisma (production, PostgreSQL) from prisma/schema.prisma
 * (development and tests, SQLite). The two only differ in the datasource provider.
 *
 *   npm run db:postgres:sync
 *
 * Run it after every change to prisma/schema.prisma, then create a migration:
 *   npm run db:postgres:migration -- <name>
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync('prisma/schema.prisma', 'utf8');
if (!source.includes('provider = "sqlite"')) {
  throw new Error('prisma/schema.prisma is expected to use provider = "sqlite"');
}

const header = [
  '// GENERATED by scripts/sync-postgres-schema.mjs – do not edit.',
  '// Edit prisma/schema.prisma and run `npm run db:postgres:sync` instead.',
  '',
].join('\n');

mkdirSync('prisma/postgres', { recursive: true });
writeFileSync('prisma/postgres/schema.prisma', header + source.replace('provider = "sqlite"', 'provider = "postgresql"'));
console.log('prisma/postgres/schema.prisma updated');
